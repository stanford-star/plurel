"""Write a markdown report from saved benchmark results, never from new runs: per workload and size
the median of every phase over its runs with their range, throughput, peak memory and size on
disk; how much the total varies across seeds and across repeats of one seed; then every failure and
every size not attempted. With matplotlib installed it also plots time and memory against rows;
see benchmarks/README.md.

    python benchmarks/report.py benchmarks/results/2026-11-08-m4.json --out benchmarks/REPORT.md
"""

import argparse
import json
import os
import statistics
from collections import defaultdict
from pathlib import Path

PHASES = ("construct", "realize", "sample", "database", "write", "read")


def median_range(values: list[float], form: str = ".3g") -> str:
    middle = statistics.median(values)
    if len(values) == 1 or max(values) - min(values) < 0.005:
        return f"{middle:{form}}"
    return f"{middle:{form}} ({min(values):{form}}–{max(values):{form}})"


def spread(group: list[dict]) -> dict[str, float | None]:
    """Across seeds: the range of the seeds' median totals over their median. Across repeats: the
    median over seeds of each seed's range over its median, the timing noise of one draw."""
    by_seed: dict[int, list[float]] = defaultdict(list)
    for run in group:
        by_seed[run["seed"]].append(run["total_seconds"])
    medians = [statistics.median(totals) for totals in by_seed.values()]
    repeated = [totals for totals in by_seed.values() if len(totals) > 1]
    return {
        "seeds": len(by_seed),
        "across_seeds": (max(medians) - min(medians)) / statistics.median(medians)
        if len(medians) > 1
        else None,
        "across_repeats": statistics.median(
            (max(t) - min(t)) / statistics.median(t) for t in repeated
        )
        if repeated
        else None,
    }


def per_second(group: list[dict], count: str) -> float:
    return statistics.median(
        r[count] / r["seconds"]["sample"] for r in group if r["seconds"]["sample"]
    )


def summarize(runs: list[dict]) -> dict[tuple[str, int], dict[str, object]]:
    grouped: dict[tuple[str, int], list[dict]] = defaultdict(list)
    for run in runs:
        if "failure" not in run and "skipped" not in run:
            grouped[run["workload"], run["size"]].append(run)
    summary = {}
    for key, group in grouped.items():
        summary[key] = {
            "rows": int(statistics.median(r["rows"] for r in group)),
            "generated": int(statistics.median(r["generated_rows"] for r in group)),
            "cells": int(statistics.median(r["cells"] for r in group)),
            "generated_cells": int(statistics.median(r["generated_cells"] for r in group)),
            "phases": {p: [r["seconds"][p] for r in group] for p in PHASES},
            "total": [r["total_seconds"] for r in group],
            "rows_per_second": per_second(group, "generated_rows"),
            "cells_per_second": per_second(group, "generated_cells"),
            "peak": [r["peak_mib"] for r in group],
            "disk": statistics.median(r["disk_mib"] for r in group),
            **spread(group),
        }
    return summary


def plots(summary: dict, out: Path) -> list[str]:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return []
    names = []
    for field, label, file in (
        ("total", "end-to-end seconds", "time.png"),
        ("peak", "peak memory, MiB", "memory.png"),
    ):
        figure, axis = plt.subplots(figsize=(8, 5))
        for workload in sorted({w for w, _ in summary}):
            points = sorted(
                (s["rows"], statistics.median(s[field]))
                for (w, _), s in summary.items()
                if w == workload
            )
            axis.plot(*zip(*points), marker="o", label=workload)
        axis.set(xscale="log", yscale="log", xlabel="rows drawn", ylabel=label)
        axis.grid(True, which="major", alpha=0.3)
        axis.legend(fontsize=7, ncol=3)
        figure.tight_layout()
        figure.savefig(out.parent / file, dpi=120)
        plt.close(figure)
        names.append(file)
    return names


def percent(share: float | None) -> str:
    return "–" if share is None else f"{share:.0%}"


def report(results: dict, summary: dict, images: list[str], source: str) -> str:
    env = results["environment"]
    lines = [
        "# Generation benchmark",
        "",
        f"Generated by `benchmarks/report.py` from [`{source}`]({source}); rerun with the command in"
        " [benchmarks/README.md](README.md). Times are seconds, the median over every seed and repeat"
        " with the range in brackets; each run is a fresh process with no warm-up, so peak memory"
        " includes the interpreter and imports (about 190 MiB).",
        "",
        "## Environment",
        "",
        "| | |",
        "|---|---|",
        f"| commit | `{env['commit']}`{' (with local changes to plurel or the examples)' if env['dirty'] else ''} |",
        f"| when | {env['when']} |",
        f"| machine | {env['cpu']}, {env['cores']} cores, {env['memory_gib']} GiB, {env['machine']} |",
        f"| platform | {env['platform']} |",
        f"| Python | {env['python']} |",
        f"| packages | {', '.join(f'{k} {v}' for k, v in env['packages'].items())} |",
        f"| threads | {', '.join(f'{k}={v}' for k, v in env['threads'].items() if v) or 'library defaults'} |",
        "",
        "## Phases",
        "",
        "| Workload | Size | Rows (generated) | Cells (generated) | "
        + " | ".join(PHASES)
        + " | Total | Generated rows/s sampled | Generated cells/s sampled | Peak MiB | Disk MiB |",
        "|---|---:|---:|---:|" + "---:|" * len(PHASES) + "---:|---:|---:|---:|---:|",
    ]
    for (workload, size), s in sorted(summary.items()):
        phases = " | ".join(median_range(s["phases"][p]) for p in PHASES)
        lines.append(
            f"| {workload} | {size:,} | {s['rows']:,} ({s['generated']:,}) | {s['cells']:,} ({s['generated_cells']:,}) | {phases}"
            f" | {median_range(s['total'])} | {s['rows_per_second'] / 1e6:.2f}M | {s['cells_per_second'] / 1e6:.2f}M"
            f" | {median_range(s['peak'], ',.0f')} | {s['disk']:.1f} |"
        )
    lines += [
        "",
        "## Variability",
        "",
        "How far the total moves. Across seeds: the range of the seeds' median totals over their"
        " median, which mixes different draws with timing noise. Across repeats: the typical range"
        " of one seed's reruns over its median, timing noise alone.",
        "",
        "| Workload | Size | Seeds | Across seeds | Across repeats of a seed |",
        "|---|---:|---:|---:|---:|",
    ]
    lines += [
        f"| {w} | {n:,} | {s['seeds']} | {percent(s['across_seeds'])} | {percent(s['across_repeats'])} |"
        for (w, n), s in sorted(summary.items())
    ]
    attempted = [run for run in results["runs"] if "skipped" not in run]
    failures = [run for run in attempted if "failure" in run]
    lines += ["", "## Failures", ""]
    if failures:
        lines += [
            "| Workload | Size | Seed | Repeat | Kind | Message |",
            "|---|---:|---:|---:|---|---|",
        ]
        lines += [
            f"| {r['workload']} | {r['size']:,} | {r['seed']} | {r['repeat']} | {r['failure_kind']} | {r['failure']} |"
            for r in failures
        ]
    else:
        lines.append(f"None: all {len(attempted)} runs finished.")
    if skipped := [run for run in results["runs"] if "skipped" in run]:
        lines += ["", "## Not attempted", "", "| Workload | Size | Why |", "|---|---:|---|"]
        lines += [f"| {r['workload']} | {r['size']:,} | {r['skipped']} |" for r in skipped]
    if images:
        lines += ["", "## Scaling", ""] + [f"![{name}]({name})" for name in images]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("results", type=Path)
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("REPORT.md"))
    args = parser.parse_args()
    results = json.loads(args.results.read_text())
    summary = summarize(results["runs"])
    images = plots(summary, args.out)
    source = os.path.relpath(args.results.resolve(), args.out.resolve().parent)
    args.out.write_text(report(results, summary, images, str(source)))
    print(f"wrote {args.out}" + (f" and {', '.join(images)}" if images else ""))


if __name__ == "__main__":
    main()
