"""Write a markdown report from saved benchmark results, never from new runs: per workload and size
the median of every phase over its runs, with their range, then throughput, peak memory and size
on disk, then every failure. With matplotlib installed it also draws benchmarks/figures.py's
figures; see benchmarks/README.md.

    python benchmarks/report.py benchmarks/results/latest.json --out benchmarks/REPORT.md
"""

import argparse
import json
import os
import statistics
from collections import defaultdict
from pathlib import Path

from figures import draw, label

PHASES = ("construct", "realize", "sample", "database", "write", "read")
ALT = {
    "time": "Time against rows drawn",
    "memory": "Peak memory against rows drawn",
    "phases": "Share of time per phase at the largest size",
}


def median_range(values: list[float], form: str = ".3g") -> str:
    middle = statistics.median(values)
    if len(values) == 1 or max(values) - min(values) < 0.005:
        return f"{middle:{form}}"
    return f"{middle:{form}} ({min(values):{form}}–{max(values):{form}})"


def summarize(runs: list[dict]) -> dict[tuple[str, int], dict[str, object]]:
    grouped: dict[tuple[str, int], list[dict]] = defaultdict(list)
    for run in runs:
        if "failure" not in run:
            grouped[run["workload"], run["size"]].append(run)
    return {
        key: {
            "rows": int(statistics.median(r["rows"] for r in group)),
            "tables": int(statistics.median(r["tables"] for r in group)),
            "cells": int(statistics.median(r["cells"] for r in group)),
            "phases": {p: [r["seconds"][p] for r in group] for p in PHASES},
            "total": [r["total_seconds"] for r in group],
            "rows_per_second": statistics.median(r["rows"] / r["seconds"]["sample"] for r in group),
            "peak": [r["peak_mib"] for r in group],
            "disk": statistics.median(r["disk_mib"] for r in group),
        }
        for key, group in grouped.items()
    }


def report(results: dict, summary: dict, images: list[str], source: str) -> str:
    env = results["environment"]
    runs = results["runs"]
    lines = [
        "# Generation benchmark",
        "",
        f"Generated by `benchmarks/report.py` from [`{source}`]({source}); rerun with the command in"
        " [benchmarks/README.md](README.md), which describes the workloads. Times are seconds, the"
        " median of the runs with their range in brackets; each run is a fresh process with no"
        " warm-up, so peak memory includes the interpreter and imports (about 195 MiB).",
        "",
        "## Environment",
        "",
        "| | |",
        "|---|---|",
        f"| commit | `{env['commit']}`{' (with local changes to plurel)' if env['dirty'] else ''} |",
        f"| when | {env['when']} |",
        f"| machine | {env['cpu']}, {env['cores']} cores, {env['memory_gib']} GiB, {env['machine']} |",
        f"| platform | {env['platform']} |",
        f"| Python | {env['python']} |",
        f"| packages | {', '.join(f'{k} {v}' for k, v in env['packages'].items())} |",
        f"| threads | {', '.join(f'{k}={v}' for k, v in env['threads'].items() if v) or 'library defaults'} |",
        "",
        "## Phases",
        "",
        "| Workload | Tables | Rows | Cells | "
        + " | ".join(PHASES)
        + " | Total | Rows/s sampled | Peak MiB | Disk MiB |",
        "|---|---:|---:|---:|" + "---:|" * len(PHASES) + "---:|---:|---:|---:|",
    ]
    for (workload, _), s in sorted(summary.items(), key=lambda item: (item[1]["tables"], item[0])):
        phases = " | ".join(median_range(s["phases"][p]) for p in PHASES)
        lines.append(
            f"| {label(workload)} | {s['tables']} | {s['rows']:,} | {s['cells']:,} | {phases}"
            f" | {median_range(s['total'])} | {s['rows_per_second'] / 1e6:.2f}M"
            f" | {median_range(s['peak'], ',.0f')} | {s['disk']:.1f} |"
        )
    failures = [run for run in runs if "failure" in run]
    lines += ["", "## Failures", ""]
    if failures:
        lines += ["| Workload | Rows | Kind | Message |", "|---|---:|---|---|"]
        lines += [
            f"| {label(r['workload'])} | {r['size']:,} | {r['failure_kind']} | {r['failure']} |"
            for r in failures
        ]
    else:
        lines.append(f"None: all {len(runs)} runs finished.")
    if images:
        lines += ["", "## Figures", ""]
        lines += [f"![{ALT[Path(name).stem.rsplit('-', 1)[-1]]}]({name})" for name in images]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("results", type=Path)
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("REPORT.md"))
    args = parser.parse_args()
    results = json.loads(args.results.read_text())
    summary = summarize(results["runs"])
    env = results["environment"]
    machine = f"{env['cpu']}, {env['platform'].split('-')[0]}"
    folder = args.out.resolve().parent
    images = [
        os.path.relpath(path.resolve(), folder)
        for path in draw(summary, PHASES, machine, args.results)
    ]
    source = os.path.relpath(args.results.resolve(), folder)
    args.out.write_text(report(results, summary, images, str(source)))
    print(f"wrote {args.out}" + (f" and {', '.join(images)}" if images else ""))


if __name__ == "__main__":
    main()
