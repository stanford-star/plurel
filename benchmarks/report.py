"""Write a markdown report from saved benchmark results, never from new runs: for random tables and
random databases, the distribution over their draws of shape, time, throughput, memory and size on
disk; the median share of each phase; the slowest draws; every failure. With matplotlib installed
it also draws benchmarks/figures.py's figures; see benchmarks/README.md.

    python benchmarks/report.py benchmarks/results/latest.json --out benchmarks/REPORT.md
"""

import argparse
import json
import os
import statistics
from pathlib import Path

import numpy as np
from figures import LABELS, draw

PHASES = ("draw", "sample", "database", "write", "read")
MEASURES = {
    "tables": ("tables", "{:,.0f}"),
    "keys": ("keys", "{:,.0f}"),
    "rows": ("rows", "{:,.0f}"),
    "cells": ("cells", "{:,.0f}"),
    "total_seconds": ("seconds, end to end", "{:.2f}"),
    "sample_seconds": ("seconds sampling", "{:.2f}"),
    "rows_per_second": ("rows per second, end to end", "{:,.0f}"),
    "peak_mib": ("peak memory, MiB", "{:,.0f}"),
    "disk_mib": ("on disk, MiB", "{:.1f}"),
}
ALT = {"time": "Time of each draw against rows", "memory": "Peak memory of each draw against cells"}


def values(runs: list[dict], measure: str) -> list[float]:
    if measure == "sample_seconds":
        return [r["seconds"]["sample"] for r in runs]
    if measure == "rows_per_second":
        return [r["rows"] / r["total_seconds"] for r in runs]
    return [r[measure] for r in runs]


def report(results: dict, images: list[str], source: str) -> str:
    env, runs = results["environment"], results["runs"]
    done = [r for r in runs if "failure" not in r]
    kinds = [k for k in LABELS if any(r["kind"] == k for r in runs)]
    lines = [
        "# Generation benchmark",
        "",
        f"Generated by `benchmarks/report.py` from [`{source}`]({source}); rerun with the command in"
        " [benchmarks/README.md](README.md). Each draw is one table or database from the default"
        " prior, at the row counts the prior draws, in a fresh process with no warm-up; peak memory"
        " includes the interpreter and imports, about 195 MiB.",
        "",
        "## Environment",
        "",
        "| | |",
        "|---|---|",
        f"| plurel | `{env.get('plurel_commit', env['commit'])}`, the last commit to change it"
        f"{' (with local changes)' if env['dirty'] else ''} |",
        f"| harness | `{env['commit']}` |",
        f"| when | {env['when']} |",
        f"| machine | {env['cpu']}, {env['cores']} cores, {env['memory_gib']} GiB, {env['machine']} |",
        f"| platform | {env['platform']} |",
        f"| Python | {env['python']} |",
        f"| packages | {', '.join(f'{k} {v}' for k, v in env['packages'].items())} |",
        f"| threads | {', '.join(f'{k}={v}' for k, v in env['threads'].items() if v) or 'library defaults'} |",
    ]
    for kind in kinds:
        mine = [r for r in done if r["kind"] == kind and r["total_seconds"] > 0]
        failed = sum(r["kind"] == kind and "failure" in r for r in runs)
        lines += ["", f"## {LABELS[kind].capitalize()}: {len(mine)} draws, {failed} failed", ""]
        if not mine:
            continue
        lines += [
            "| | median | 90th percentile | largest | smallest |",
            "|---|---:|---:|---:|---:|",
        ]
        for measure, (name, form) in MEASURES.items():
            v = values(mine, measure)
            stats = (np.median(v), np.quantile(v, 0.9), max(v), min(v))
            lines.append(f"| {name} | " + " | ".join(form.format(x) for x in stats) + " |")
        shares = {
            p: statistics.median(r["seconds"][p] / r["total_seconds"] for r in mine) for p in PHASES
        }
        lines += [
            "",
            "Median share of the time: "
            + ", ".join(f"{p} {s:.0%}" for p, s in shares.items())
            + ".",
            "",
            "Slowest draws:",
            "",
            "| seed | tables | keys | rows | seconds | peak MiB |",
            "|---:|---:|---:|---:|---:|---:|",
        ]
        for r in sorted(mine, key=lambda r: -r["total_seconds"])[:5]:
            lines.append(
                f"| {r['seed']} | {r['tables']} | {r['keys']} | {r['rows']:,} |"
                f" {r['total_seconds']:.2f} | {r['peak_mib']:,.0f} |"
            )
    failures = [r for r in runs if "failure" in r]
    lines += ["", "## Failures", ""]
    if failures:
        lines += ["| kind | seed | how | message |", "|---|---:|---|---|"]
        lines += [
            f"| {r['kind']} | {r['seed']} | {r['failure_kind']} | {r['failure']} |"
            for r in failures
        ]
    else:
        lines.append(f"None: all {len(runs)} draws finished.")
    if images:
        lines += ["", "## Figures", ""]
        lines += [f"![{ALT[Path(name).stem.rsplit('-', 1)[-1]]}]({name})" for name in images]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("results", type=Path)
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("REPORT.md"))
    args = parser.parse_args()
    results = json.loads(args.results.read_text())
    env = results["environment"]
    machine = f"{env['cpu']}, {env['platform'].split('-')[0]}"
    folder = args.out.resolve().parent
    images = [
        os.path.relpath(path.resolve(), folder)
        for path in draw(results["runs"], machine, args.results)
    ]
    source = os.path.relpath(args.results.resolve(), folder)
    args.out.write_text(report(results, images, str(source)))
    print(f"wrote {args.out}" + (f" and {', '.join(images)}" if images else ""))


if __name__ == "__main__":
    main()
